// Command gen writes plugins/all/all_gen.go, which imports every company plugin
// folder so its init function registers it. A company folder is any direct
// subfolder of plugins/ containing non-test Go files, except all, internal,
// and shared.
//
// Run from the bff module root: go run ./plugins/internal/gen
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	pluginsDir = "plugins"
	outFile    = "plugins/all/all_gen.go"
	modulePath = "jobapps/bff"
)

var skip = map[string]bool{"all": true, "internal": true, "shared": true}

func main() {
	// go generate runs this from plugins/all; walk up to the module root.
	for range 3 {
		if _, err := os.Stat("go.mod"); err == nil {
			break
		}
		if err := os.Chdir(".."); err != nil {
			log.Fatal(err)
		}
	}
	entries, err := os.ReadDir(pluginsDir)
	if err != nil {
		log.Fatalf("gen: run from the bff module root: %v", err)
	}

	var pkgs []string
	for _, e := range entries {
		if !e.IsDir() || skip[e.Name()] || strings.HasPrefix(e.Name(), ".") || strings.HasPrefix(e.Name(), "_") {
			continue
		}
		if hasGoFiles(filepath.Join(pluginsDir, e.Name())) {
			pkgs = append(pkgs, e.Name())
		}
	}
	sort.Strings(pkgs)

	var b bytes.Buffer
	b.WriteString("// Code generated by plugins/internal/gen. DO NOT EDIT.\n\n")
	b.WriteString("// Package all imports every company plugin so it registers itself.\n")
	b.WriteString("// Regenerate after adding or removing a plugin folder: go run ./plugins/internal/gen\n")
	b.WriteString("package all\n\n")
	if len(pkgs) > 0 {
		b.WriteString("import (\n")
		for _, p := range pkgs {
			fmt.Fprintf(&b, "\t_ %q\n", modulePath+"/"+pluginsDir+"/"+p)
		}
		b.WriteString(")\n")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gen: %v", err)
	}
	if old, err := os.ReadFile(outFile); err == nil && bytes.Equal(old, src) {
		return
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		log.Fatalf("gen: %v", err)
	}
	fmt.Printf("gen: wrote %s (%d plugins)\n", outFile, len(pkgs))
}

func hasGoFiles(dir string) bool {
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	for _, f := range files {
		if !strings.HasSuffix(f, "_test.go") {
			return true
		}
	}
	return false
}
